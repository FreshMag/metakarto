    acceptAllOfOrThrow(
        names.map { listOf(it) },
        variations = variations,
        message = message,
        block = block,
    )

/**
 * Visits the element with the provided [name]. Returns the result of [block] if the element is present, otherwise
 * null.
 */
fun <T> Visitor.acceptOrNull(
    name: String,
    variations: Boolean = false,
    block: (Element) -> T,
): T? =
    (if (variations) e.findAny(variationsOf(name)) else e.find(name))
        .visitOrNull(block)

/**
 * Visits the element with the provided [name]. Throws an [IllegalArgumentException] with [message] if the element
 * is missing.
 */
@Throws(IllegalArgumentException::class)
fun <T> Visitor.accept(
    name: String,
    variations: Boolean = false,
    message: String = "Required element missing: $name",
    block: (Element) -> T,
): T =
    acceptOrNull(name, variations, block)
        ?: throw IllegalArgumentException(message)

/**
 * Visits the elements with the provided [name1] and [name2]. If [variations] is true, variations of the names are
 * also accepted. Returns the result of [block] if both elements are present, otherwise null.
 */
fun <T> Visitor.acceptOrNull(
    name1: String,
    name2: String,
    variations: Boolean = false,
    block: (Element, Element) -> T,
): T? =
    acceptAllOfOrNull(name1, name2, variations = variations) { list ->
        val (elem1, elem2) = list
        block(elem1, elem2)
    }

