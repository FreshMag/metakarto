 *
 * Note: variations are not considered by default.
 */
@Throws(IllegalArgumentException::class)
fun <T> Visitor.acceptAllOfOrThrow(
    vararg names: String,
    variations: Boolean = false,
    message: String = "Missing at least one of the required elements: ${names.joinToString()}",
    block: (List<Element>) -> T,
